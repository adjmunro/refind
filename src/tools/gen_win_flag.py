#!/usr/bin/env python3
"""Generate src/icons/os_win.svg: the Vista-era waving four-pane flag.

The flag is a 2x2 grid of panes mapped through a gentle wave, so each pane is
a smooth curved quad. Tweak the constants below and re-run to reshape it.
"""
import math
import pathlib

OUT = pathlib.Path(__file__).resolve().parents[1] / "icons" / "os_win.svg"

X0, Y0 = 36.0, 62.0      # top-left of the flag
W, H = 184.0, 146.0      # flag size before waving
GAP = 0.05               # gap between panes, as a fraction of W/H
SAG = 22.0               # how far the middle of the flag dips
RISE = 30.0              # the right edge sits this much higher than the left
LEAN = 16.0              # the top of the left edge leans right
STEPS = 32               # samples per pane edge


def warp(u, v):
    x = X0 + W * u + LEAN * (1 - v) * (1 - u) ** 2
    y = Y0 + H * v + SAG * math.sin(math.pi * u) ** 1.3 - RISE * u
    # the right half turns away slightly, so it's a touch shorter
    y = y - 0.08 * H * (v - 0.5) * u
    return x, y


def pane(u0, u1, v0, v1):
    pts = []
    pts += [warp(u0 + (u1 - u0) * i / STEPS, v0) for i in range(STEPS + 1)]
    pts += [warp(u1, v0 + (v1 - v0) * i / STEPS) for i in range(1, STEPS + 1)]
    pts += [warp(u1 - (u1 - u0) * i / STEPS, v1) for i in range(1, STEPS + 1)]
    pts += [warp(u0, v1 - (v1 - v0) * i / STEPS) for i in range(1, STEPS)]
    return "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z"


g = GAP / 2
panes = [pane(0, 0.5 - g, 0, 0.5 - g), pane(0.5 + g, 1, 0, 0.5 - g),
         pane(0, 0.5 - g, 0.5 + g, 1), pane(0.5 + g, 1, 0.5 + g, 1)]

OUT.write_text(
    '<?xml version="1.0" encoding="UTF-8"?>\n'
    "<!-- Windows: Vista-era waving flag. Generated by src/tools/gen_win_flag.py; edit that, not this. -->\n"
    '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">\n'
    '  <g fill="#ffffff" stroke="#ffffff" stroke-width="3" stroke-linejoin="round">\n'
    + "".join(f'    <path d="{d}"/>\n' for d in panes)
    + "  </g>\n</svg>\n"
)
print(f"wrote {OUT}")
