#!/usr/bin/env python3
"""Generate src/icons/os_cachyos.svg from the CachyOS logo shipped by the distro.

The official logo is a faceted "C" in cyan/teal with three bubbles. This keeps
its geometry but flattens it to two tones so it can be recoloured per theme:
the outline and cyan facets become the glyph colour (#ffffff), the darker teal
facets become the shade colour (#999999), and the gradient highlights are dropped.

Usage: gen_cachyos.py [path/to/cachyos.svg]   (default /usr/share/icons/cachyos.svg)
"""
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

SRC = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/icons/cachyos.svg")
OUT = pathlib.Path(__file__).resolve().parents[1] / "icons" / "os_cachyos.svg"
SVG = "{http://www.w3.org/2000/svg}"
TONES = {"#ffffff": "#ffffff", "#00ccff": "#ffffff", "#00aa88": "#999999"}

root = ET.parse(SRC).getroot()
shapes = []


def walk(node, transforms):
    t = node.get("transform")
    if t:
        transforms = transforms + [t]
    tag = node.tag.replace(SVG, "")
    if tag in ("path", "circle"):
        m = re.search(r"fill:\s*([^;]+)", node.get("style", ""))
        fill = (m.group(1) if m else node.get("fill", "")).strip().lower()
        if fill in TONES:
            attrs = {k: node.get(k) for k in ("d", "cx", "cy", "r") if node.get(k) is not None}
            shapes.append((tag, attrs, TONES[fill], transforms))
    for child in node:
        if child.tag.replace(SVG, "") != "defs":
            walk(child, transforms)


walk(root, [])
vb = root.get("viewBox", "0 0 64 64").split()
body = []
for tag, attrs, fill, transforms in shapes:
    a = " ".join(f'{k}="{v}"' for k, v in attrs.items())
    el = f'<{tag} {a} fill="{fill}"/>'
    for t in reversed(transforms):
        el = f'<g transform="{t}">{el}</g>'
    body.append("      " + el)

# Fit the logo's viewBox into the middle ~78% of a 256 canvas.
OUT.write_text(
    '<?xml version="1.0" encoding="UTF-8"?>\n'
    "<!-- CachyOS: two-tone flattening of the official logo. Generated by src/tools/gen_cachyos.py; edit that, not this. -->\n"
    '<svg xmlns="http://www.w3.org/2000/svg" width="256" height="256" viewBox="0 0 256 256">\n'
    f'  <svg x="22" y="22" width="212" height="212" viewBox="{" ".join(vb)}">\n'
    + "\n".join(body)
    + "\n  </svg>\n</svg>\n"
)
print(f"wrote {OUT} ({len(shapes)} shapes)")
